WITH
	BOUNDS AS (
		SELECT
			MIN(ORDER_DATE) AS MIN_DATE,
			MAX(ORDER_DATE) AS MAX_DATE
		FROM
			{{ ref('stg_orders') }}
	),
	DAYS AS (
		SELECT
			GENERATE_SERIES(MIN_DATE, MAX_DATE, INTERVAL '1 day')::DATE AS FULL_DATE
		FROM
			BOUNDS
	)
SELECT
	TO_CHAR(FULL_DATE, 'YYYYMMDD')::INTEGER AS DATE_ID,
	FULL_DATE,
	EXTRACT(
		YEAR
		FROM
			FULL_DATE
	)::INTEGER AS YEAR,
	EXTRACT(
		QUARTER
		FROM
			FULL_DATE
	)::INTEGER AS QUARTER,
	EXTRACT(
		MONTH
		FROM
			FULL_DATE
	)::INTEGER AS MONTH,
	TO_CHAR(FULL_DATE, 'FMMonth') AS MONTH_NAME,
	EXTRACT(
		DAY
		FROM
			FULL_DATE
	)::INTEGER AS DAY,
	EXTRACT(
		ISODOW
		FROM
			FULL_DATE
	)::INTEGER AS DAY_OF_WEEK,
	TO_CHAR(FULL_DATE, 'FMDay') AS DAY_NAME,
	CASE
		WHEN EXTRACT(
			ISODOW
			FROM
				FULL_DATE
		) IN (6, 7) THEN TRUE
		ELSE FALSE
	END AS IS_WEEKEND,
	DATE_TRUNC('month', FULL_DATE) AS MONTH_START
FROM
	DAYS